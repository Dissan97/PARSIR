LOOKAHEAD=${1:-1.0}
ALPHA=${2:-0.1}

rm -rf ../bin/balanced
rm -rf ../bin/unbalanced
mkdir -p ../bin/balanced
mkdir -p ../bin/unbalanced
echo "Building all files for 40 cores configuration"
# PCS balanced
make pcs THREADS=40 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD  #ORGINAL
make pcs QUEUE_IMPL=LPTF THREADS=40 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD  #LPTF
make pcs NUMA=1 THREADS=40 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD  # ORGINAL-NUMA
make pcs QUEUE_IMPL=LPTF NUMA=1 THREADS=40 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD  #LPTF-NUMA
#PCS unblanced
make pcs THREADS=40 UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD  #ORGINAL
make pcs QUEUE_IMPL=LPTF THREADS=40 UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD  #LPTF
make pcs NUMA=1 THREADS=40 UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD  # ORGINAL-NUMA
make pcs QUEUE_IMPL=LPTF NUMA=1 THREADS=40 UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD  #LPTF-NUMA
# HIGHWAY
make highway THREADS=40 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD  #ORGINAL
