LOOKAHEAD=${1:-1.0}
ALPHA=${2:-0.1}
OBJECTS=${4:-1024}
THREADS=${3:-40}
rm -rf ../bin/balanced
rm -rf ../bin/unbalanced
mkdir -p ../bin/balanced
mkdir -p ../bin/unbalanced
echo "Building all files for 40 cores configuration"
# PCS balanced
make pcs ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #ORGINAL
make pcs QUEUE_IMPL=LPTF ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #LPTF
make pcs NUMA=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  # ORGINAL-NUMA
make pcs QUEUE_IMPL=LPTF NUMA=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #LPTF-NUMA
#PCS unblanced
make pcs UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #ORGINAL
make pcs QUEUE_IMPL=LPTF UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #LPTF
make pcs NUMA=1 UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  # ORGINAL-NUMA
make pcs QUEUE_IMPL=LPTF NUMA=1 UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #LPTF-NUMA
# HIGHWAY
make highway ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #ORGINAL
make highway QUEUE_IMPL=LPTF ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #LPTF
make highway NUMA=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  # ORGINAL-NUMA
make highway QUEUE_IMPL=LPTF NUMA=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #LPTF-NUMA
# HIGHWAY unblanced
make highway UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #ORGINAL
make highway QUEUE_IMPL=LPTF UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #LPTF
make highway NUMA=1 UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  # ORGINAL-NUMA
make highway QUEUE_IMPL=LPTF NUMA=1 UNBALANCE=1 ALPHA=$ALPHA LOOKAHEAD=$LOOKAHEAD OBJECTS=$OBJECTS THREADS=$THREADS  #LPTF-NUMA

mv ../bin/*UNBALANCE ../bin/unbalanced
mv ../bin/*BALANCE ../bin/balanced
